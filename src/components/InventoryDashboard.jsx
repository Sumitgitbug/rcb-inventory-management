function buildAutoNoteFromAsset({ noteId, createdAt, assetForm, quantity, serialNumbers, assetIds }) {
  const articleName =
    [assetForm.subCategory, assetForm.make, assetForm.model].filter(Boolean).join(" - ") ||
    assetForm.category ||
    "Asset"
  const supplierName =
    assetForm.supplierName.trim() ||
    "Unknown Supplier"
  const supplyOrderNo = assetForm.supplyOrderNo.trim() || assetForm.invoiceNo.trim()
  const invoiceNo = assetForm.invoiceNo.trim()
  const serialText = serialNumbers.filter(Boolean).join(", ")

  return {
    id: `note-${createdAt}`,
    noteId,
    inoteDate: assetForm.purchaseDate || todayISO(),
    supplierName,
    dateOfReceipt: assetForm.supplyDate || assetForm.orderDate || assetForm.purchaseDate || todayISO(),
    dateOfDelivery: assetForm.supplyDate || assetForm.orderDate || assetForm.purchaseDate || "",
    supplyOrderNo,
    supplyOrderDate: assetForm.orderDate || "",
    invoiceNo,
    invoiceDate: assetForm.purchaseDate || todayISO(),
    items: [
      {
        articleName,
        quantityTendered: String(quantity),
        quantityAccepted: String(quantity),
        quantityRejected: "0",
        remarks: serialText || assetForm.model.trim() || assetForm.make.trim() || "",
      },
    ],
    sourceAssetIds: assetIds,
    autoGenerated: true,
    createdAt,
    updatedAt: createdAt,
  }
}

function normalizeSerials(values, quantity) {
  const serials = [...values]
  while (serials.length < quantity) serials.push("")
  return serials.slice(0, quantity)
}

function buildIssueCounts(issues) {
  const counts = new Map()
  issues.forEach((issue) => {
    if (normalizeIssueStatus(issue.status) === "returned") return
    const key = String(issue.assetId || "").trim()
    if (!key) return
    counts.set(key, (counts.get(key) ?? 0) + 1)
  })
  return counts
}

function hasMeaningfulInventoryState(state) {
  return Boolean(
    state &&
      (
        (state.assets?.length ?? 0) > 0 ||
        (state.employees?.length ?? 0) > 0 ||
        (state.issues?.length ?? 0) > 0 ||
        (state.notes?.length ?? 0) > 0 ||
        (state.catalog?.types?.length ?? 0) > 0 ||
        Object.keys(state.counters ?? {}).length > 0
      ),
  )
}

async function toDataUrl(file) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader()
    reader.onload = () => resolve(String(reader.result || ""))
    reader.onerror = () => reject(new Error("Failed to read file"))
    reader.readAsDataURL(file)
  })
}

function generateNoteId(inventory) {
  const year = new Date().getFullYear().toString().slice(-2)
  const noteCounters = inventory.counters?.noteCounter ?? 0
  const nextCounter = noteCounters + 1
  const noteId = `RCB/INOTE/${year}/${String(nextCounter).padStart(3, '0')}`
  return { noteId, nextCounter }
}

function escapeCsvCell(value) {
  return `"${String(value ?? "").replace(/"/g, '""')}"`
}

function buildAssetsCsv(assets, catalog) {
  const headers = [
    "assetId",
    "type",
    "category",
    "subCategory",
    "make",
    "model",
    "quantity",
    "serialNumbers",
    "invoiceNo",
    "purchaseDate",
    "orderDate",
    "supplyDate",
    "availableQuantity",
  ]

  const rows = assets.map((asset) => [
    asset.assetId,
    getTypeLabel(catalog, asset.type),
    asset.category || "",
    asset.subCategory || "",
    asset.make || "",
    asset.model || "",
    asset.quantity ?? 1,
    (asset.serialNumbers ?? []).filter(Boolean).join("|"),
    asset.invoiceNo || "",
    asset.purchaseDate || "",
    asset.orderDate || "",
    asset.supplyDate || "",
    asset.availableQuantity ?? "",
  ])

  return [headers, ...rows]
    .map((row) => row.map(escapeCsvCell).join(","))
    .join("\n")
}

function buildStocksCsv(assets, catalog) {
  return buildAssetsCsv(assets, catalog)
}

function toFileSlug(value) {
  return String(value ?? "")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "") || "stocks"
}

function downloadTextFile(filename, content, mimeType = "text/plain;charset=utf-8") {
  const blob = new Blob([content], { type: mimeType })
  const url = URL.createObjectURL(blob)
  const anchor = document.createElement("a")
  anchor.href = url
  anchor.download = filename
  anchor.click()
  window.setTimeout(() => URL.revokeObjectURL(url), 0)
}

